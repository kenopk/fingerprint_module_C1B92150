#pragma once

#include <stdint.h>
#include <stddef.h>

// =====================================================================================
// fp_serial.h - транспорт UART: нижний слой между протоколом модуля и UART платформы.
//
// Что умеет слой: открыть порт, отправить байты, принять байты с таймаутом, выбросить
// непринятое, сменить скорость. Больше ничего. Про пакеты, команды и контрольные суммы
// слой не знает: это дело протокола (fp_module), который вызывает только функции отсюда.
// Про UART платформы (драйвер IDF, его типы и константы) в заголовке ничего нет: параметры
// задаются обычными числами, а перевод в типы IDF делается внутри fp_serial.cpp.
//
// Модуль отпечатков: UART 3,3 В, 57600 бод, 8 бит данных, без чётности, 1 стоп-бит (8N1).
// Подключение: TX ESP (GPIO2) -> RX модуля, RX ESP (GPIO3) <- TX модуля, UART1.
//
// Правило возврата для всех функций (тип int):
//   0 и больше - успех (у TX и RX это число байт);
//   меньше нуля - ошибка, одно из чисел таблицы ниже.
// До успешного fp_serial_init все остальные функции возвращают ошибку (-2).
//
// ПОТОКОБЕЗОПАСНОСТЬ (решение на будущее, когда появится больше одной задачи)
//   Что уже защищено. Драйвер UART в IDF сам берёт свои внутренние мьютексы на запись, чтение и
//   сброс приёмного буфера (в исходниках драйвера tx_mux и rx_mux), поэтому ОТДЕЛЬНЫЙ вызов
//   fp_serial_TX, fp_serial_RX или fp_serial_reset_buffer из двух задач сразу не испортит байты
//   друг друга. Отдельный замок внутри fp_serial поэтому не добавляется: он ничего бы не дал.
//   Что НЕ защищено, и как это обходится:
//   1. fp_serial_init не рассчитан на параллельный вызов (проверка "порт уже открыт" и запись
//      номера порта не атомарны). Правило: вызывать один раз при старте в app_main, ДО создания
//      других задач.
//   2. Пара "отправить команду -> принять ответ" между двумя вызовами НЕ атомарна: пока задача A
//      ждёт ответ, задача B могла бы отправить свою команду, и ответы перепутаются. Это защищается
//      НЕ здесь, а в слое протокола (fp_module): мьютекс FreeRTOS берётся на всю транзакцию
//      "сбросить буфер -> отправить команду -> принять ответ" и отпускается на любом пути выхода.
//      Для этого в fp_module нужен отдельный код ошибки "модуль занят другой задачей".
//   3. fp_serial_speed во время чужой передачи может сменить скорость на полпути. Правило:
//      менять скорость только когда модулем никто не пользуется.
//   Сейчас модулем пользуется одна задача (app_main), этого достаточно.
// =====================================================================================

// -------------------------------------------------------------------------------------
// КОДЫ ОШИБОК (отрицательные числа, которые возвращают функции этого слоя)
// Каждому отдельному способу сломаться свой код, чтобы вызывающий мог реагировать по-разному.
// Порядок проверок внутри каждой функции: сначала состояние порта (-2 или -3), потом
// аргументы (-1), потом вызовы драйвера (-4, -5). Возвращается код первой сработавшей проверки.
// Рекомендуется завести для них имена (например, enum FP_SERIAL_ERR_ARG и т.д.) вместо чисел.
//
//   -1  FP_SERIAL_ERR_ARG          неверный аргумент: нулевой указатель вместо буфера, Length равен
//                                  нулю (TX), скорость 0 или меньше, Data_Bits не из 5...8, Stop_Bits
//                                  не 1 и не 2, номер порта вне допустимого диапазона. Ничего не
//                                  выполнялось. Реакция: исправить вызов.
//   -2  FP_SERIAL_ERR_NOT_OPEN     порт не открыт: функция вызвана до успешного fp_serial_init (или
//                                  init не удался). Реакция: вызвать fp_serial_init.
//   -3  FP_SERIAL_ERR_ALREADY_OPEN порт уже открыт: повторный вызов fp_serial_init. Только init.
//                                  Первый порт при этом не затрагивается.
//   -4  FP_SERIAL_ERR_DRIVER       отказ драйвера платформы: любой вызов IDF вернул ошибку (установка
//                                  драйвера, применение параметров, назначение пинов, запись, чтение,
//                                  сброс буфера, смена скорости). Для init порт остаётся закрытым.
//                                  Это проблема нашей стороны, а не модуля; повторять обычно бессмысленно.
//   -5  FP_SERIAL_ERR_TX_TIMEOUT   не удалось дождаться окончания передачи: байты приняты драйвером, но
//                                  за отведённое время (100 мс) не ушли на линию или ожидание вернуло
//                                  ошибку. Только TX. Данные могли быть отправлены частично.
enum { // коды ошибок, возвращаемые функциями этого слоя
    FP_SERIAL_ERR_ARG = -1,
    FP_SERIAL_ERR_NOT_OPEN = -2,
    FP_SERIAL_ERR_ALREADY_OPEN = -3,
    FP_SERIAL_ERR_DRIVER = -4,
    FP_SERIAL_ERR_TX_TIMEOUT = -5
};
// Кто какие коды может вернуть:
//   fp_serial_init          0, -1, -3, -4
//   fp_serial_TX            число байт (больше нуля), -1, -2, -4, -5
//   fp_serial_RX            число байт (0 и больше), -1, -2, -4
//   fp_serial_reset_buffer  0, -2, -4
//   fp_serial_speed         0, -1, -2, -4
// Примечание: "за Timeout ничего не пришло" в RX - это успех с результатом 0, а не код ошибки.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// fp_serial_init - открыть порт: проверить параметры, настроить UART, привязать пины.
// Вызывается один раз, до остальных функций. Порядок параметров ниже обязателен, в нём
// легко ошибиться: СНАЧАЛА пин RX, ПОТОМ пин TX.
//   Baudrate_Prot - скорость в бодах (для модуля 57600). Ноль недопустим;
//   Data_Bits     - число бит данных в кадре: 5, 6, 7 или 8 (для модуля 8);
//   Stop_Bits     - число стоп-бит: 1 или 2 (для модуля 1);
//   RX_Pin        - номер GPIO, на который ESP ПРИНИМАЕТ данные (идёт с TX модуля), у нас 3;
//   TX_Pin        - номер GPIO, с которого ESP ПЕРЕДАЁТ данные (идёт на RX модуля), у нас 2;
//   Num_Port      - номер аппаратного UART. У ESP32-C6 обычных UART два: 0 и 1. Порт 0 занят
//                   консолью (монитор и прошивка), для модуля нужен порт 1.
// ЧЁТНОСТЬ В ПАРАМЕТРАХ НЕТ: слой всегда работает без чётности (для модуля это верно).
//   Что такое чётность. Это необязательный бит в кадре UART, который стоит после бит данных и
//   перед стоп-битом. Отправитель выставляет его так, чтобы число единиц среди бит данных ПЛЮС
//   этот бит было:
//     - чётным (режим "чётность even"), либо
//     - нечётным (режим "нечётность odd").
//   Примеры для режима even: байт 0x13 = 00010011 содержит три единицы (нечётно), поэтому бит
//   чётности равен 1 (стало четыре, чётно); байт 0xEF = 11101111 содержит семь единиц, бит равен 1;
//   байт 0x00 содержит ноль единиц, бит равен 0. В режиме odd бит всегда противоположный.
//   Зачем нужна. Приёмник сам пересчитывает число единиц и сверяет с принятым битом. Если одиночный
//   бит исказила помеха, чётность не сойдётся, и приёмник узнаёт, что байт повреждён.
//   Ограничения. Она замечает только НЕЧЁТНОЕ число искажённых бит: если исказились два бита
//   одновременно, чётность сойдётся, и ошибка пройдёт незамеченной. Исправить ошибку она не может,
//   только обнаружить. Бит увеличивает кадр с 10 до 11 бит (при 57600 это чуть медленнее).
//   Почему здесь не нужна. Формат кадра у передатчика и приёмника ДОЛЖЕН совпадать: модуль
//   работает без чётности (8N1), и если включить её у ESP, кадры перестанут совпадать, а байты
//   будут приниматься с ошибками или теряться (по описанию кадра, лично на модуле не проверялось).
//   Целостность данных проверяется на уровне пакета: контрольной суммой пакета модуля, которая
//   охватывает все байты от PID до данных. Параметр чётности пригодился бы для другого устройства
//   с чётностью (например, 8E1); тогда его надо будет добавить в fp_serial_init.
//   В IDF для чётности есть три режима: выключена (значение 0), even (2) и odd (3); числа не равны
//   значениям из таблицы переводов, поэтому перевод делается явно.
// Типичный вызов для модуля: fp_serial_init(57600, 8, 1, 3, 2, 1).
// Возвращает 0 при успехе. Ошибки: -3 порт уже открыт; -1 неверный параметр (например,
// Data_Bits = 9); -4 отказ драйвера. Если вернулась ошибка, порт остаётся закрытым и init можно
// вызвать снова.
// -------------------------------------------------------------------------------------
int fp_serial_init(int Baudrate_Prot,int Data_Bits,int Stop_Bits, int8_t RX_Pin,int8_t TX_Pin,int8_t Num_Port); // инициализация UART порта

// -------------------------------------------------------------------------------------
// fp_serial_TX - отправить Length байт из Data и дождаться, пока они реально уйдут на линию.
//   Data   - откуда брать байты; функция их не меняет (поэтому const), массив может быть
//            константным;
//   Length - сколько байт отправить, больше нуля.
// Возвращается, когда последний байт ушёл по проводу, а не просто лёг в очередь: иначе приём
// ответа мог бы начаться, пока команда ещё передаётся.
// Возвращает число отправленных байт (равно Length при успехе). Ошибки: -2 порт не открыт;
// -1 Data равен nullptr или Length равен нулю; -4 отказ драйвера при записи; -5 не дождались
// окончания передачи.
// Команду отправляй одним вызовом, не по одному байту: паузы между байтами могут быть приняты
// модулем за конец пакета (не проверено на модуле).
// -------------------------------------------------------------------------------------
int fp_serial_TX(const uint8_t *Data, uint32_t Length); // передача данных по UART порту ОТПРАВКА

// -------------------------------------------------------------------------------------
// fp_serial_RX - принять до Length байт в Data, ждать не дольше Timeout миллисекунд.
//   Data    - буфер, куда класть принятые байты; в нём должно быть место минимум на Length байт;
//   Length  - сколько байт нужно принять, БОЛЬШЕ нуля (ноль - ошибка аргумента, -1);
//   Timeout - сколько ждать, в МИЛЛИСЕКУНДАХ (общее время, а не на каждый байт). Ноль РАЗРЕШЁН:
//             он значит "не ждать, вернуть то, что уже лежит в приёмном буфере" (быстрая проверка
//             без блокировки). Результат при этом может быть меньше Length или равен 0.
// Задача, вызвавшая функцию, на время ожидания блокируется (другие задачи работают).
// Возвращается раньше таймаута, когда набралось Length байт. Если за Timeout пришло меньше,
// функция ждёт весь таймаут и возвращает сколько пришло (это подтверждено опытом: при запросе
// 32 байт и пришедших 12 она ждала весь таймаут и вернула 12). Поэтому просить "с запасом" нельзя:
// запрашивай ровно столько байт, сколько точно придёт.
// Возвращает число принятых байт, от 0 до Length. Ноль значит "за Timeout ничего не пришло" и
// ошибкой НЕ является. Ошибки: -2 порт не открыт; -1 Data равен nullptr или Length равен нулю;
// -4 отказ драйвера.
// Если принято меньше Length, это не ошибка транспорта: решать, что делать с оборванным
// пакетом, должен вызывающий.
// Таймаут переводится в тики FreeRTOS (в этом проекте CONFIG_FREERTOS_HZ = 100, то есть 1 тик = 10 мс)
// делением нацело с округлением ВНИЗ: значения 1...9 мс превращаются в 0 тиков и ведут себя как
// Timeout = 0 (не ждать). Для таймаутов в сотни миллисекунд (800, 1500) это не мешает.
// -------------------------------------------------------------------------------------
int fp_serial_RX(uint8_t *Data,uint32_t Length, uint32_t Timeout); // прием данных по UART порту ПРИЕМ

// -------------------------------------------------------------------------------------
// fp_serial_reset_buffer - выбросить всё, что уже принято портом, но ещё не прочитано.
// Вызывай ПЕРЕД отправкой каждой команды: так остатки прошлого ответа или шум на линии не
// попадут в разбор нового ответа. Именно перед отправкой: после неё можно выбросить начало
// уже пришедшего ответа. Передачу функция не отменяет.
// Возвращает 0 при успехе. Ошибки: -2 порт не открыт; -4 отказ драйвера.
// -------------------------------------------------------------------------------------
int fp_serial_reset_buffer(void);   // очистка буфера UART порта

// -------------------------------------------------------------------------------------
// fp_serial_speed - сменить скорость уже открытого порта на лету.
//   Baudrate_Prot - новая скорость в бодах, больше нуля.
// Меняется только скорость UART на стороне ESP. Скорость самого модуля задана внутри модуля
// (по умолчанию 57600) и этой функцией не меняется. Реальная скорость может чуть отличаться
// от заданной из-за округления делителя.
// Возвращает 0 при успехе. Ошибки: -2 порт не открыт; -1 скорость 0 или меньше; -4 отказ драйвера
// (например, такую скорость получить нельзя).
// -------------------------------------------------------------------------------------
int fp_serial_speed(uint32_t Baudrate_Prot);    // установка скорости UART порта
