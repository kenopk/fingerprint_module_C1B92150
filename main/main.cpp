// РАСПИНОВКА МОДУЛЯ И ПОДКЛЮЧЕНИЕ К ESP32-C6
// Разъём модуля на 6 контактов (на плате отмечены 1 и 6). Распиновка взята с картинки листинга,
// цвета проводов определены по порядку на разъёме; прозвонка "провод -> площадка" не делалась.
//
//   Конт. | Имя модуля | Назначение                         | Провод  | Куда на ESP32-C6
//   ------+------------+------------------------------------+---------+----------------------------
//     1   | GND        | земля                              | белый   | GND
//     2   | UART_RX    | вход модуля (он принимает)         | синий   | GPIO2  (это TX ESP)
//     3   | UART_TX    | выход модуля (он передаёт)         | зелёный | GPIO3  (это RX ESP)
//     4   | VCC_MCU    | питание логики модуля, 3,3 В       | жёлтый  | 3V3
//     5   | TOUCH_OUT  | сигнал касания                     | чёрный  | GPIO6  (пока не используется)
//     6   | VCC_3.3V   | питание сенсора, 3,3 В             | красный | 3V3
//
// Правило UART: TX одной стороны идёт на RX другой (перекрест), поэтому TX ESP (GPIO2) соединён
// с RX модуля (синий), а RX ESP (GPIO3) с TX модуля (зелёный). Порт UART1, 57600 бод, 8N1.
//
// Остальные выводы проекта:
//   GPIO7        - выход замка (планируется): светодиод или транзистор с реле, импульс 1 с.
//                  Реле напрямую к GPIO не подключать: нужны транзистор и защитный диод.
//   GPIO16/17    - консоль UART0 (монитор и прошивка через USB-UART мост на плате, порт COM9,
//                  монитор 115200). Эти выводы заняты, модулю их не отдавать.
//
// Питание: 3,3 В (по листингу 3,3 +- 0,3 В, ток меньше 40 мА). 5 В на модуль подавать нельзя.
// Оба вывода питания (жёлтый и красный) идут на 3V3. Резистор около 100 Ом в красном проводе
// должен быть убран: сенсор питается напрямую от 3V3.
//
// Что подтверждено на железе (прошлый проект): обмен по GPIO2/GPIO3 на 57600 работает (модуль
// ответил на VfyPwd), значит синий и зелёный провода и GND подключены верно, а питание логики
// модуля (жёлтый) достаточно. Не подтверждено: питание сенсора (красный) под нагрузкой (нужна
